#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

echo "=== Building OhGnomesApp (Release / Debug) ==="
cd "${ROOT_DIR}"
swift build -c release --product OhGnomesApp

BIN_PATH="${ROOT_DIR}/.build/arm64-apple-macosx/release/OhGnomesApp"
APP_DIR="${ROOT_DIR}/dist/Oh! Gnomes.app"
CONTENTS_DIR="${APP_DIR}/Contents"
MACOS_DIR="${CONTENTS_DIR}/MacOS"
RESOURCES_DIR="${CONTENTS_DIR}/Resources"

echo "=== Packaging Application Bundle: ${APP_DIR} ==="
rm -rf "${APP_DIR}"
mkdir -p "${MACOS_DIR}"
mkdir -p "${RESOURCES_DIR}"

cp "${BIN_PATH}" "${MACOS_DIR}/OhGnomesApp"
chmod +x "${MACOS_DIR}/OhGnomesApp"

# Copy resources bundle if generated by SPM
if [ -d "${ROOT_DIR}/.build/arm64-apple-macosx/release/OhGnomes_GnomesCore.bundle" ]; then
    cp -R "${ROOT_DIR}/.build/arm64-apple-macosx/release/OhGnomes_GnomesCore.bundle" "${RESOURCES_DIR}/"
fi

# Copy Content directory into app resources
cp -R "${ROOT_DIR}/Content" "${RESOURCES_DIR}/"
cp -R "${ROOT_DIR}/WebController" "${RESOURCES_DIR}/"

# Write Info.plist
cat << 'EOF' > "${CONTENTS_DIR}/Info.plist"
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleName</key>
    <string>Oh! Gnomes</string>
    <key>CFBundleDisplayName</key>
    <string>Oh! Gnomes</string>
    <key>CFBundleIdentifier</key>
    <string>com.echopost.oh-gnomes</string>
    <key>CFBundleVersion</key>
    <string>1.0.0</string>
    <key>CFBundleShortVersionString</key>
    <string>1.0.0</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleExecutable</key>
    <string>OhGnomesApp</string>
    <key>LSMinimumSystemVersion</key>
    <string>13.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSSupportsAutomaticGraphicsSwitching</key>
    <true/>
    <key>NSPrincipalClass</key>
    <string>NSApplication</string>
</dict>
</plist>
EOF

echo "=== Packaging Complete: ${APP_DIR} ==="
ls -la "${APP_DIR}/Contents"
